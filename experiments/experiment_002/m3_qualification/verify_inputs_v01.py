#!/usr/bin/env python3
"""Check frozen generator reproduces existing inspected OD trips and topology."""
import argparse,hashlib,json,xml.etree.ElementTree as ET
from pathlib import Path

def digest(path):
    h=hashlib.sha256()
    with open(path,"rb") as f:
        for chunk in iter(lambda:f.read(1024*1024),b""):h.update(chunk)
    return h.hexdigest()

def topology(path):
    root=ET.parse(path).getroot()
    edges=[]
    for e in root.findall("edge"):
        if e.get("function") in ("internal","crossing","walkingarea") or e.get("id","").startswith(":"):continue
        lanes=tuple(sorted((l.get("index"),l.get("speed"),l.get("length")) for l in e.findall("lane")))
        edges.append((e.get("id"),e.get("from"),e.get("to"),lanes))
    connections=tuple(sorted((c.get("from"),c.get("to"),c.get("fromLane"),c.get("toLane"))
                             for c in root.findall("connection") if not (c.get("from","").startswith(":") or c.get("to","").startswith(":"))))
    return tuple(sorted(edges)),connections

def trips(path):
    root=ET.parse(path).getroot()
    v=[]
    for t in root.findall("trip"):
        v.append((t.get("id"),t.get("from"),t.get("to"),float(t.get("depart"))))
    if len(v)!=1000 or len(set(x[0] for x in v))!=1000:raise RuntimeError("Expected 1000 unique vehicle trips")
    return tuple(v)

def compare(a,b,c,d,seed,window):
    if int(seed)!=2101 or int(window) not in (200,600,1200):
        raise RuntimeError("Generator qualification cannot inspect other seeds")
    t0=topology(a);t1=topology(b)
    od0=trips(c);od1=trips(d)
    net_equal=t0==t1
    trip_equal=od0==od1
    report=dict(status="PASS" if net_equal and trip_equal else "FAIL",
        qualifier_seed=seed,window_seconds=window,
        archived_network_sha256=digest(a),regenerated_network_sha256=digest(b),
        archived_trips_sha256=digest(c),regenerated_trips_sha256=digest(d),
        normalized_edges=len(t0[0]),normalized_connections=len(t0[1]),
        normalized_topology_equal=net_equal,seed_specific_od_and_depart_schedule_equal=trip_equal,
        reference="archives from preexisting M2 run 40446073958; regenerated with frozen input generator, pinned SUMO 1.28.0 image",
        caution="Byte hashes may differ due to autogenerated XML metadata; comparison is normalized graph and exact OD/schedule tuples")
    if not net_equal or not trip_equal:raise RuntimeError("Frozen generator no longer matches development reference")
    return report

def main():
    p=argparse.ArgumentParser()
    for name in ("archived-net","regenerated-net","archived-trips","regenerated-trips","report"):
        p.add_argument("--"+name,required=True)
    p.add_argument("--seed",type=int,required=True);p.add_argument("--window",type=int,required=True)
    a=p.parse_args()
    obj=compare(a.archived_net,a.regenerated_net,a.archived_trips,a.regenerated_trips,a.seed,a.window)
    Path(a.report).write_text(json.dumps(obj,indent=2)+"\n")
    print(json.dumps(obj,indent=2))

if __name__=="__main__":main()
